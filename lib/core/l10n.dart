/// Strings of deferred chunks (ADR-057: the notifications page, the reminder
/// sheet, the install guides): each chunk registers its own table before it
/// builds, so its text never weighs on `main.dart.js`.
final Map<String, List<String>> _chunkStrings = {};
final Set<Object> _registeredChunks = {};

/// Adds a deferred chunk's strings (idempotent per [table]).
void registerStrings(Map<String, List<String>> table) {
  if (_registeredChunks.add(table)) _chunkStrings.addAll(table);
}

extension L10nX on BuildContext {
  bool get isAr => Localizations.localeOf(this).languageCode == 'ar';

  /// Translated UI string; `{name}` placeholders replaced from [args].
  String tr(String key, [Map<String, String> args = const {}]) {
    final pair = _strings[key] ?? _chunkStrings[key];
    var s = pair == null ? key : (isAr ? pair[0] : pair[1]);
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }

  /// «بعد ٣ أيام» for a day [n] days ahead, with the Arabic count rules
  /// (ADR-054): 1 «غدًا», 2 «بعد يومين», 3–10 «بعد ٣ أيام», 11+ «بعد ١١
  /// يومًا», Arabic-Indic digits. English: "Tomorrow" / "In {n} days".
  String inDays(int n) {
    if (n == 1) return tr('tomorrow');
    if (!isAr) return tr('inDays', {'n': '$n'});
    if (n == 2) return tr('inTwoDays');
    return tr(n >= 3 && n <= 10 ? 'inDays' : 'inManyDays', {'n': toArabicDigits('$n')});
  }

  /// «٥ أيام» / «يومين» / «١٢ يومًا» (Arabic count rules, ADR-054); "5 days".
  String dayCount(int n) => switch (n) {
        1 => tr('dayCountOne'),
        2 => tr('dayCountTwo'),
        _ => tr(n >= 3 && n <= 10 ? 'dayCountFew' : 'dayCountMany', {'n': isAr ? toArabicDigits('$n') : '$n'}),
      };

  /// Translated UI string, or null when [key] has no entry.
  String? trOrNull(String key) => _strings.containsKey(key) ? tr(key) : null;

  /// Picks the Arabic or English variant of a bilingual content field,
  /// falling back to whichever is non-empty.
  String pick(String ar, String en) {
    if (isAr) return ar.isNotEmpty ? ar : en;
    return en.isNotEmpty ? en : ar;
  }
}
